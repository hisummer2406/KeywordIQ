/**
 * 名次升降的共享色值。
 *
 * 由趋势小图与「排名变化」「排名变化率」两列共同引用。同一语义在同一屏上使用两组不同
 * 色值，会让用户把色差误读成含义差别——这里曾有过：列用 #3f8600/#cf1322，小图用
 * #52c41a/#ff4d4f。
 *
 * **取深色一组的判据是对比度。** 这组 token 同时服务于两列小字与一条 2px 折线，须由更严
 * 的场景（小字）决定取值：#52c41a 在白底上约 2.6:1，达不到 WCAG AA 对正文的 4.5:1；
 * #3f8600 约 5.5:1。深绿画线依然清晰，反之亮绿写字则偏淡。
 *
 * **共享的是色值，不是口径。** 小图的颜色表达整段走势（窗口首点 vs 末点），排名变化列
 * 表达相邻两期之比，二者不同是设计使然：前者回答「这一周走势如何」，后者回答「较上一期
 * 如何」。在真实数据上约三分之一的行两者方向相反，那不是 bug。**不要**为了「让它们看起来
 * 一致」把小图颜色改由 ranking_change 驱动——那会让一条整周下跌的折线因末期回升而显示为
 * 绿色。`TrendSparkline.test.tsx` 有一条回归专门拦这个改法。
 *
 * 不放进 Umi 主题变量：这三个色值表达的是业务语义（名次升降），不是品牌色。放进主题会让
 * 它们看起来可以被换肤，而换掉绿红会直接改变数据的含义。
 */
export const TREND_COLORS = {
  /** 名次上升（排名数值变小） */
  up: '#3f8600',
  /** 名次下降（排名数值变大） */
  down: '#cf1322',
  /** 无变化 */
  flat: '#1677ff',
} as const;

/**
 * 图上排名标签的颜色。
 *
 * 刻意用中性灰而非升降色：折线本身已承载颜色，数字再着色会与之相争，且七个彩色数字会让
 * 「整段是红是绿」这个第一眼信息变得难找。
 */
export const TREND_LABEL_COLOR = '#595959';
